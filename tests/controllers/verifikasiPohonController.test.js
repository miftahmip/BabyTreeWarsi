      const pohon = buatPohonDenganMonitoring([
        { id: 'a', monitoring: { tahap_monitoring: 1 } }
      ]);

      const { monitoring1 } =
        VerifikasiPohonController
          ._kelompokkanMonitoringPerTahap([pohon]);

      expect(monitoring1[0].pohon).toBe(pohon);
